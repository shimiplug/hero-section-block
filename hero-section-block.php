define( 'HERO_SECTION_VERSION', '1.0.0' );
define( 'HERO_SECTION_DIR_URL', plugin_dir_url( __FILE__ ) );
define( 'HERO_SECTION_DIR_PATH', plugin_dir_path( __FILE__ ) );

if ( ! class_exists( 'Hero_Section_Plugin' ) ) {

	/**
	 * Registers the Hero Section block.
	 */
	class Hero_Section_Plugin {

		/**
		 * Editor script handle generated by register_block_type() from block.json.
		 */
		const EDITOR_SCRIPT_HANDLE = 'hero-section-hero-section-editor-script';

		/**
		 * Hooks the plugin into WordPress.
		 */
		public function __construct() {
			add_action( 'init', array( $this, 'on_init' ) );
		}

		/**
		 * Registers the block and its editor translations.
		 */
		public function on_init() {

			register_block_type( __DIR__ . '/build' );

			$this->load_script_translations();
		}

		/**
		 * Makes the strings in the editor bundle translatable.
		 *
		 * Safe to call unconditionally: if the handle is not registered the call
		 * is a no-op.
		 */
		public function load_script_translations() {

			wp_set_script_translations(
				self::EDITOR_SCRIPT_HANDLE,
				'hero-section',
				HERO_SECTION_DIR_PATH . 'languages'
			);
		}
	}

	new Hero_Section_Plugin();
}
